#!/usr/bin/env bash
set -euo pipefail
TASK_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
export AIOT_ESPDET_RUNTIME=1
export IDF_TOOLS_PATH="$TASK_ROOT/experiments/vlm_split/vendor/idf-tools"
source "$TASK_ROOT/experiments/vlm_split/vendor/esp-idf-v5.3.6/export.sh"
cd "$TASK_ROOT"
idf.py -B experiments/moq/vendor/build \
 -D SDKCONFIG="$TASK_ROOT/experiments/moq/private/sdkconfig" \
 -D AIOT_MOQT_EXPERIMENT=ON \
 -D AIOT_MOQT_PIN_HEADER="$TASK_ROOT/experiments/moq/private/pin.h" \
 -D AIOT_MOBILITY_RESEARCH=ON -D AIOT_MOBILITY_CAMERA=ON -D AIOT_ESPDET_RUNTIME=ON \
 -D AIOT_PIPELINE_PROFILE=OFF -D AIOT_QUIC_BATCH_EXPERIMENT=OFF \
 -D AIOT_ESP32_HW_AES=OFF -D AIOT_QUIC_PSRAM_POOL=ON \
 -D AIOT_QUIC_CIPHER_LIST=TLS13-CHACHA20-POLY1305-SHA256 \
 -D AIOT_MOQT_CONCURRENT="${AIOT_MOQT_CONCURRENT:-OFF}" -D AIOT_PROFILE_AI_CORE=1 \
 -D AIOT_MOQT_BOUNDED_PUMP="${AIOT_MOQT_BOUNDED_PUMP:-OFF}" \
 -D AIOT_MOQT_IMAGE_SLOTS="${AIOT_MOQT_IMAGE_SLOTS:-2}" \
 -D AIOT_MOQT_PREVIEW_KBPS="${AIOT_MOQT_PREVIEW_KBPS:-0}" \
 -D AIOT_MOQT_PREVIEW_UNACKED_KB="${AIOT_MOQT_PREVIEW_UNACKED_KB:-0}" \
 -D AIOT_MOQT_DELIVERY_TIMEOUT_RESET="${AIOT_MOQT_DELIVERY_TIMEOUT_RESET:-0}" \
 -D AIOT_MOQT_POLICY_EXPERIMENT="${AIOT_MOQT_POLICY_EXPERIMENT:-OFF}" \
 -D AIOT_MOQT_REPLAY_INPUT="${AIOT_MOQT_REPLAY_INPUT:-${AIOT_MOQT_POLICY_EXPERIMENT:-OFF}}" \
 -D AIOT_MOQT_POLICY="${AIOT_MOQT_POLICY:-1}" -D AIOT_MOQT_FIFO_ADMISSION="${AIOT_MOQT_FIFO_ADMISSION:-0}" \
 -D AIOT_MOQT_PREVIEW_DEADLINE_MS="${AIOT_MOQT_PREVIEW_DEADLINE_MS:-2000}" \
 -D AIOT_MOQT_AI_DEADLINE_MS="${AIOT_MOQT_AI_DEADLINE_MS:-5000}" \
 -D AIOT_MOQT_AUDIT="${AIOT_MOQT_AUDIT:-OFF}" \
 -D AIOT_MOQT_WIRE_PROFILE="${AIOT_MOQT_WIRE_PROFILE:-OFF}" \
 -D AIOT_MOQT_EVENT_EVIDENCE="${AIOT_MOQT_EVENT_EVIDENCE:-OFF}" \
 -D AIOT_MOQT_EVIDENCE_DELIVERY="${AIOT_MOQT_EVIDENCE_DELIVERY:-0}" \
 -D AIOT_MOQT_CACHE_KB="${AIOT_MOQT_CACHE_KB:-1024}" \
 -D AIOT_MOQT_CACHE_OBJECTS="${AIOT_MOQT_CACHE_OBJECTS:-16}" \
 -D AIOT_MOQT_KEEP_CACHE="${AIOT_MOQT_KEEP_CACHE:-OFF}" \
 -D AIOT_MOQT_RECONNECT_LIMIT="${AIOT_MOQT_RECONNECT_LIMIT:-0}" \
 -D AIOT_MOQT_MISSION_COUNT="${AIOT_MOQT_MISSION_COUNT:-OFF}" \
 -D AIOT_MOQT_PASSAGE_LINE="${AIOT_MOQT_PASSAGE_LINE:-128}" \
 -D AIOT_MOQT_PASSAGE_AXIS="${AIOT_MOQT_PASSAGE_AXIS:-0}" \
 -D AIOT_MOQT_PASSAGE_DIRECTION="${AIOT_MOQT_PASSAGE_DIRECTION:-1}" \
 -D AIOT_MOQT_PASSAGE_STEP="${AIOT_MOQT_PASSAGE_STEP:-48}" \
 -D AIOT_MOQT_RESULT_CACHE_OBJECTS="${AIOT_MOQT_RESULT_CACHE_OBJECTS:-32}" \
 -D AIOT_MOQT_EXT_LIMITS="${AIOT_MOQT_EXT_LIMITS:-OFF}" \
 -D AIOT_MOQT_EXT_SOURCE_TIMEOUT="${AIOT_MOQT_EXT_SOURCE_TIMEOUT:-OFF}" \
 -D PROJECT_VER=moqt21-audit-v7 \
 -D AIOT_OTA_SITE_HEADER="$TASK_ROOT/experiments/ota/private/ota_site.h" build
